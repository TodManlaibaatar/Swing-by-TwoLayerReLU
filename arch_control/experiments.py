"""Pre-specified experiment definitions (see PROTOCOL.md).

Every run is fully described by a RunSpec.  Data and isotropic initializations
are generated by the repository's own ``make_data`` / ``init_model`` so that the
canonical ReLU run (seed 0) reproduces the archived trajectory.
"""
from __future__ import annotations

import hashlib
import itertools
import json
import math
import sys
from dataclasses import asdict, dataclass, replace
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

import theory_guided_swing_by_phase_diagram as tg  # noqa: E402
from full_flow_diagnostic import Config  # noqa: E402

from .simulate import unit  # noqa: E402

CANONICAL = dict(mu1=3.0, mu2=2.0, sigma=0.15)
PREDECESSOR = dict(mu1=1.0, mu2=2.0, sigma=0.05)   # Yang et al. (2025), Fig. 2(c) data
GRID_MU2 = (1.8, 2.0, 2.2)
GRID_SIGMA = (0.12, 0.15, 0.18)
NAMED_PROBES = ("comp_pop", "comp_emp", "m85", "p176", "e1", "e2", "neg_e1", "neg_e2")


@dataclass(frozen=True)
class RunSpec:
    exp: str
    arch: str            # relu | linear | tied
    mu1: float
    mu2: float
    sigma: float         # isotropic per-coordinate noise std (sigma1 = sigma2)
    n_per_cluster: int
    width: int
    epsilon: float       # per-neuron initial norm
    init: str            # iso | pos | pos_entries
    seed: int
    dt: float
    t_end: float
    log_dt: float = 0.01
    save_params: bool = False

    @property
    def run_id(self) -> str:
        blob = json.dumps(asdict(self), sort_keys=True).encode()
        tag = hashlib.sha256(blob).hexdigest()[:10]
        return (f"{self.exp}__{self.arch}__mu{self.mu1:g}-{self.mu2:g}_sd{self.sigma:g}"
                f"__h{self.width}_eps{self.epsilon:.2e}_{self.init}__s{self.seed}"
                f"__dt{self.dt:g}__{tag}")

    @property
    def batch_key(self):
        return (self.arch, self.width, 2 * self.n_per_cluster, self.dt, self.t_end,
                self.log_dt, self.save_params)

    def cfg(self) -> Config:
        return replace(Config(), mu1=self.mu1, mu2=self.mu2, sigma1=self.sigma,
                       sigma2=self.sigma, n_per_cluster=self.n_per_cluster,
                       width=self.width, epsilon=self.epsilon, dt=self.dt,
                       max_time=self.t_end, seed=self.seed)


def make_inputs(spec: RunSpec):
    """Return (X, labels, U0, W0, named_probe_matrix) for one run."""
    cfg = spec.cfg()
    X, labels = tg.make_data(cfg)
    if spec.init == "iso":
        U0, W0, _ = tg.init_model(cfg)                      # archived convention
    elif spec.init == "pos":                               # angles in the open positive quadrant
        rng = np.random.default_rng(spec.seed)
        phi = rng.uniform(0.0, math.pi / 2, size=spec.width)
        U0 = spec.epsilon * np.column_stack([np.cos(phi), np.sin(phi)]); W0 = U0.copy()
    elif spec.init == "pos_entries":                       # predecessor: all entries positive
        rng = np.random.default_rng(spec.seed)
        U0 = spec.epsilon * rng.uniform(0.5, 1.5, size=(spec.width, 2)); W0 = U0.copy()
    else:
        raise ValueError(spec.init)
    comp_pop = np.array([spec.mu1, spec.mu2]); comp_pop /= np.linalg.norm(comp_pop)
    emp = np.array([X[labels == 0, 0].mean(), X[labels == 1, 1].mean()])
    comp_emp = emp / np.linalg.norm(emp)
    named = np.stack([comp_pop, comp_emp, unit(-85.0), unit(176.0),
                      unit(0.0), unit(90.0), unit(180.0), unit(-90.0)])
    return X, labels, U0, W0, named


def _seeds(n):
    return tuple(range(n))


def experiment_specs(name: str) -> list[RunSpec]:
    """The frozen experiment list.  Changing anything here changes run ids."""
    out = []
    if name == "E1_canonical":          # headline matched control, long horizon
        for arch, seed in itertools.product(("relu", "linear"), _seeds(10)):
            out.append(RunSpec("E1_canonical", arch, **CANONICAL, n_per_cluster=2000,
                               width=200, epsilon=1e-3, init="iso", seed=seed, dt=2e-4,
                               t_end=20.0, save_params=(seed == 0)))
    elif name == "E2_grid":             # preregistered nine-cell grid, both architectures
        for arch, mu2, sd, seed in itertools.product(("relu", "linear"), GRID_MU2,
                                                     GRID_SIGMA, _seeds(5)):
            out.append(RunSpec("E2_grid", arch, 3.0, mu2, sd, 2000, 200, 1e-3, "iso",
                               seed, 2e-4, 10.0))
    elif name == "E3_regime":           # width / init-scale / init-geometry sweep
        for data, arch, h, s0, init, seed in itertools.product(
                (CANONICAL, PREDECESSOR), ("relu", "linear"), (2, 8, 32, 200),
                (2e-4, 2e-2), ("iso", "pos"), _seeds(10)):
            eps = 1e-3 if (h == 200 and s0 == 2e-4) else math.sqrt(s0 / h)
            t_end = 20.0 if data is CANONICAL else 40.0   # weaker concept (mu=1) is slower
            out.append(RunSpec("E3_regime", arch, data["mu1"], data["mu2"], data["sigma"],
                               2000, h, eps, init, seed, 2e-4, t_end))
    elif name == "E4_positive_control":  # predecessor's symmetric model, all-positive init
        for dprime, omega, seed in itertools.product((2, 4), (0.01, 0.05), _seeds(10)):
            out.append(RunSpec("E4_positive_control", "tied", **PREDECESSOR,
                               n_per_cluster=2000, width=dprime, epsilon=omega,
                               init="pos_entries", seed=seed, dt=2e-4, t_end=60.0))
    elif name == "E5_stepsize":         # integrator refinement for the canonical seed
        for arch, dt in itertools.product(("relu", "linear"), (2e-4, 1e-4)):
            out.append(RunSpec("E5_stepsize", arch, **CANONICAL, n_per_cluster=2000,
                               width=200, epsilon=1e-3, init="iso", seed=0, dt=dt,
                               t_end=10.0))
    else:
        raise KeyError(name)
    return out


ALL_EXPERIMENTS = ("E1_canonical", "E5_stepsize", "E4_positive_control", "E2_grid",
                   "E3_regime")


def smoke_specs() -> list[RunSpec]:
    """Tiny configuration for a < 2 minute end-to-end check (not a protocol run)."""
    out = []
    for arch in ("relu", "linear"):
        out.append(RunSpec("SMOKE", arch, **CANONICAL, n_per_cluster=200, width=20,
                           epsilon=1e-2, init="iso", seed=0, dt=1e-3, t_end=2.0,
                           save_params=True))
    out.append(RunSpec("SMOKE", "tied", **PREDECESSOR, n_per_cluster=200, width=2,
                       epsilon=0.05, init="pos_entries", seed=0, dt=1e-3, t_end=5.0))
    return out
